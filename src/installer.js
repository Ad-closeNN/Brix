/**
 * Installer Module - `brix init installer` and `brix make <target>`
 * 
 * Supported Installer Types:
 * ==========================
 * 1. zip (portable) - Pure Node.js archiver, no external tools required
 * 2. inno - Inno Setup (iscc.exe), modern wizard, LZMA2 compression
 * 3. nsis - NSIS (makensis.exe), classic script-based installer
 * 4. msi - WiX Toolset (candle.exe + light.exe), Windows Installer format
 * 
 * Build Pipeline:
 * ===============
 * 1. brix init installer → creates installer/installer.json + script template
 * 2. brix make <target> → renders template → invokes toolchain → output in installer/dist/
 * 
 * Template Variables:
 * ===================
 * {{APP_NAME}}        - Application name
 * {{APP_VERSION}}     - Version string
 * {{OUT_BASE}}        - Output filename base
 * {{OUTPUT_DIR}}      - Output directory
 * {{ICON}}            - Path to icon file
 * {{EXE}}             - Path to application exe
 * {{EXE_NAME}}        - Exe filename
 * {{EXTRA_FILES}}     - Additional files (per-installer format)
 * {{UPGRADE_GUID}}    - WiX upgrade GUID
 * {{DIR_ENTRIES}}     - WiX directory structure
 * {{FEATURE_REFS}}    - WiX component references
 * 
 * Security:
 * =========
 * - No arbitrary code execution in templates
 * - File paths resolved relative to project root
 * - Path traversal prevented by resolve_scoped_path logic
 * - Toolchain invoked with explicit arguments (no shell injection)
 */
