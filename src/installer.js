function toForwardSlashes(p) {
    return p.replace(/\\/g, '/');
}

/**
 * Generates a Windows-style GUID with uppercase hex and braces.
 * Used for WiX component GUIDs (must be stable per component).
 * Uses crypto.randomUUID() for cryptographic randomness.
 */
function guid() {
    const g = require('crypto').randomUUID();
    return `{${g.toUpperCase()}}`;
}

/**
 * Locates an external tool (iscc, makensis, candle, light, wix) in PATH
 * or common default install directories.
 * 
 * Search order:
 * 1. PATH directories with platform-specific extensions
 * 2. Common default install directories (hardcoded fallbacks)
 * 
 * Returns full path to tool executable or null if not found.
 * Used by makeInstaller to locate iscc, makensis, candle, light, wix.
 */
async function findTool(name) {
    const exts = process.platform === 'win32' ? ['', '.exe', '.cmd', '.bat'] : [''];
    const dirs = (process.env.PATH || '').split(path.delimiter);
    for (const dir of dirs) {
        if (!dir) continue;
        for (const ext of exts) {
            const candidate = path.join(dir, name + ext);
            if (await fs.pathExists(candidate)) return candidate;
        }
    }
    // Common default install locations (fallback when not in PATH)
    const fixed = {
        iscc: [
            'C:/Program Files (x86)/Inno Setup 6/iscc.exe',
            'C:/Program Files/Inno Setup 6/iscc.exe',
            'C:/Program Files (x86)/Inno Setup 5/iscc.exe'
        ],
        makensis: [
            'C:/Program Files (x86)/NSIS/makensis.exe',
            'C:/Program Files/NSIS/makensis.exe'
        ],
        candle: [
            'C:/Program Files (x86)/WiX Toolset v3.11/bin/candle.exe',
            'C:/Program Files (x86)/WiX Toolset v3.14/bin/candle.exe',
            'C:/Program Files/WiX Toolset v3.11/bin/candle.exe'
        ]
    };
    for (const candidate of fixed[name] || []) {
        if (await fs.pathExists(candidate)) return candidate;
    }
    return null;
}

/**
 * Executes a command and returns {code, out, err}.
 * Uses execFile (not shell) for security - no shell injection possible.
 * WindowsHide prevents console window flash.
 * maxBuffer increased to 16MB for large installer output.
 */
function run(cmd, args, cwd) {
    return new Promise((resolve) => {
        execFile(cmd, args, { cwd, windowsHide: true, maxBuffer: 16 * 1024 * 1024 }, (err, stdout, stderr) => {
            resolve({ code: err ? (err.code || 1) : 0, out: String(stdout || ''), err: String(stderr || '') });
        });
    });
}

let pipedLines = null;
let pipedIndex = 0;

function readPipedLine() {
    if (pipedLines === null) {
        // Non-TTY stdin (pipe/file): read everything once at the first
        // prompt, then hand out one line per prompt.
        pipedLines = String(fs.readFileSync(0, 'utf8')).split(/\r?\n/);
        pipedIndex = 0;
    }
    return pipedIndex < pipedLines.length ? pipedLines[pipedIndex++] : '';
}

/**
 * Interactive list picker (arrow keys; space toggles in multi mode).
 * Falls back to a numbered prompt when stdin is not a TTY.
 */
function promptList({ message, choices, multi = false, defaults = [] }) {
    const renderChoices = () => choices.map((c, i) => {
        const label = typeof c === 'string' ? c : c.label;
        const hint = typeof c === 'string' ? '' : c.hint ? chalk.gray('  ' + c.hint) : '';
        return { label, hint, i };
    });

    if (!process.stdin.isTTY || !process.stdout.isTTY) {
        return new Promise((resolve) => {
            const list = renderChoices();
            console.log('\n' + chalk.bold(message));
            for (const item of list) {
                console.log(`  ${item.i + 1}. ${item.label}${item.hint}`);
            }
            const answer = readPipedLine().trim();
            console.log(chalk.gray(multi ? 'Enter numbers (comma-separated, empty = all):' : 'Enter number: ') + answer);
            if (multi && answer === '') {
                resolve(list.map((x) => x.i)); // empty = select everything
                return;
            }
            const nums = multi
                ? answer.split(/[,\s]+/).filter(Boolean).map((n) => parseInt(n, 10) - 1)
                : [parseInt(answer, 10) - 1];
            const picked = nums.filter((n) => !Number.isNaN(n) && n >= 0 && n < list.length);
            if (picked.length === 0) {
                console.log(chalk.red(multi ? 'No valid choices.' : 'Invalid choice.'));
                resolve(multi ? [] : -1);
                return;
            }
            resolve(multi ? picked : picked[0]);
        });
    }

    return new Promise((resolve) => {
        const rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: true });
        const selected = new Set(defaults);
        let cursor = 0;
        const list = renderChoices();
        let drawn = false;

        const draw = () => {
            const lines = [chalk.bold(message)];
            for (const item of list) {
                const marker = item.i === cursor ? chalk.cyan('❯') : ' ';
                const check = multi ? (selected.has(item.i) ? chalk.green('[✓]') : '[ ]') : '';
                const label = item.i === cursor ? chalk.cyan(item.label) : item.label;
                lines.push(` ${marker} ${check} ${label}${item.hint}`);
            }
            lines.push(chalk.gray(multi ? 'space: toggle · enter: done · esc: cancel' : '↑/↓: move · enter: select · esc: cancel'));
            const out = '\x1B[2K\r' + lines.join('\r\n\x1B[2K') + '\r\n';
            if (drawn) process.stdout.write(`\x1B[${lines.length}A`);
            process.stdout.write(out);
            drawn = true;
        };

        const onKey = (str, key) => {
            if (key.name === 'up' || (key.ctrl && key.name === 'p')) {
                cursor = (cursor - 1 + list.length) % list.length;
            } else if (key.name === 'down' || (key.ctrl && key.name === 'n')) {
                cursor = (cursor + 1) % list.length;
            } else if (multi && key.name === 'space') {
                selected.has(cursor) ? selected.delete(cursor) : selected.add(cursor);
            } else if (key.name === 'return' || key.name === 'enter') {
                cleanup();
                resolve(multi ? Array.from(selected) : cursor);
            } else if (key.name === 'escape') {
                cleanup();
                resolve(multi ? null : -1);
            }
            draw();
        };

        const cleanup = () => {
            process.stdin.setRawMode(false);
            rl.close();
            process.stdout.write('\x1B[?25h');
        };

        rl.input.on('keypress', onKey);
        process.stdin.setRawMode(true);
        process.stdin.resume();
        process.stdout.write('\x1B[?25l');
        draw();
    });
}

async function loadProjectConfig(project) {
    let root = project ? path.resolve(project) : process.cwd();
    let stat = await fs.stat(root).catch(() => null);
    if (stat && stat.isFile()) root = path.dirname(root);
    const configPath = path.join(root, '.brix');
    if (!(await fs.pathExists(configPath))) {
        throw new Error(`No .brix file found in ${root} — run "brix build" there first`);
    }
    const config = await fs.readJson(configPath);
    return { root, config };
}

function findBuiltExe(root, config) {
    const outDir = path.join(root, 'Brix_Works');
    if (!fs.existsSync(outDir)) return null;
    const exeName = sanitize(config.name || 'BrixApp') + '.exe';
    const exact = path.join(outDir, exeName);
    if (fs.existsSync(exact)) return exact;
    const exes = fs.readdirSync(outDir).filter((f) => f.toLowerCase().endsWith('.exe'));
    return exes.length ? path.join(outDir, exes[0]) : null;
}

function sanitize(name) {
    return name.replace(/[<>:"/\\|?*\x00-\x1F]/g, '_').replace(/\s+/g, '-');
}

async function listProjectFiles(root) {
    const { glob } = require('glob');
    const ignore = ['node_modules', 'node_modules/**', '.git', '.git/**', 'Brix_Works', 'Brix_Works/**', '.brix', '.brix/**', 'installer', 'installer/**', '*.log', '*.WebView2', 'temp_*.zip'];
    const matched = await glob(['./**/*'], { cwd: root, ignore, nodir: true, dot: true });
    const out = [];
    for (const f of matched) {
        const abs = path.join(root, f);
        try {
            const st = await fs.stat(abs);
            if (st.isFile()) out.push({ name: toForwardSlashes(f), size: st.size });
        } catch (e) { /* skip */ }
    }
    return out.sort((a, b) => a.name.localeCompare(b.name));
}

const INSTALL_IGNORED_DIRS = new Set(['node_modules', '.git', 'Brix_Works', 'installer', 'BRIX-APP']);
const INSTALL_IGNORED_FILES = new Set(['.brix', '.brix.json']);

/**
 * Top-level folders + root files for the installer picker. Picking a folder
 * includes every file under it (destination = the folder's relative path).
 */
async function listProjectItems(root) {
    const folders = [];
    const files = [];
    const entries = await fs.readdir(root, { withFileTypes: true }).catch(() => []);
    for (const e of entries) {
        if (e.isDirectory() && !INSTALL_IGNORED_DIRS.has(e.name)) {
            const count = await countFilesUnder(path.join(root, e.name));
            if (count > 0) folders.push({ name: toForwardSlashes(e.name), count });
        } else if (e.isFile() && !INSTALL_IGNORED_FILES.has(e.name)) {
            const st = await fs.stat(path.join(root, e.name)).catch(() => null);
            if (st) files.push({ name: e.name, size: st.size });
        }
    }
    folders.sort((a, b) => a.name.localeCompare(b.name));
    files.sort((a, b) => a.name.localeCompare(b.name));
    return { folders, files };
}

async function countFilesUnder(dir) {
    let n = 0;
    const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
    for (const e of entries) {
        if (e.isDirectory()) {
            if (!INSTALL_IGNORED_DIRS.has(e.name)) n += await countFilesUnder(path.join(dir, e.name));
        } else if (e.isFile()) n += 1;
    }
    return n;
}

/**
 * Every file under a picked folder, with `subDir` = path relative to root
 * (the folder's own name is preserved as the destination).
 */
async function collectFolderFiles(root, folder) {
    const out = [];
    const base = path.join(root, folder);
    const walk = async (dir, rel) => {
        const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
        for (const e of entries) {
            if (e.isDirectory()) {
                if (!INSTALL_IGNORED_DIRS.has(e.name)) await walk(path.join(dir, e.name), rel ? `${rel}/${e.name}` : e.name);
            } else if (e.isFile()) {
                const abs = path.join(dir, e.name);
                const st = await fs.stat(abs).catch(() => null);
                if (st) out.push({ path: toForwardSlashes(path.relative(root, abs)), subDir: toForwardSlashes(rel || ''), size: st.size });
            }
        }
    };
    await walk(base, folder);
    return out.sort((a, b) => a.path.localeCompare(b.path));
}

function formatBytes(b) {
    if (b < 1024) return `${b} B`;
    if (b < 1024 * 1024) return `${(b / 1024).toFixed(1)} KB`;
    return `${(b / 1024 / 1024).toFixed(1)} MB`;
}

async function listInstallerTemplates() {
    const out = [];
    for (const [type, meta] of Object.entries(TYPES)) {
        const tool = meta.tools[0];
        const found = tool ? await findTool(tool) : null;
        out.push({
            type,
            label: meta.label,
            hint: found ? chalk.green('✓ ' + tool) : chalk.red('tool not found')
        });
    }
    return out;
}

async function writeInstallerConfig(root, config) {
    const dir = path.join(root, 'installer');
    await fs.ensureDir(dir);
    if (config.type === 'msi' && !config.upgradeGuid) {
        config.upgradeGuid = guid(); // stable across builds so MSI upgrades work
    }
    await fs.writeJson(path.join(dir, 'installer.json'), config, { spaces: 2 });
    const meta = TYPES[config.type];
    if (meta.template) {
        const script = renderTemplate(meta.template, config, root);
        await fs.writeFile(path.join(dir, `installer.${meta.ext}`), script, 'utf8');
    }
}

/**
 * Renders an installer template by substituting variables with config values.
 * 
 * Template Variables:
 * - {{APP_NAME}}, {{APP_VERSION}}, {{OUT_BASE}}, {{OUTPUT_DIR}}, {{ICON}}
 * - {{EXE}}, {{EXE_NAME}} - application executable path/name
 * - {{EXTRA_FILES}} - installer-specific file listing format
 * - {{DIR_ENTRIES}}, {{FEATURE_REFS}} - WiX directory/component XML
 * - {{UPGRADE_GUID}} - stable WiX upgrade GUID for MajorUpgrade
 * 
 * Security: All file paths resolved via path.resolve() to prevent traversal.
 * Paths normalized to forward slashes for installer compatibility.
 * 
 * @param {string} template - Raw template string (INNO_TEMPLATE, NSIS_TEMPLATE, or WIX_TEMPLATE)
 * @param {Object} cfg - Installer config from installer.json
 * @param {string} root - Project root directory
 * @returns {string} Rendered installer script ready for toolchain
 */
function renderTemplate(template, cfg, root) {
    let exeName = cfg.exeName || 'app.exe';
    const outputDir = path.join(cfg.outputDir || path.join(root, 'installer', 'dist')).replace(/\\/g, '/');
    const iconPath = cfg.icon ? path.resolve(root, cfg.icon).replace(/\\/g, '/') : '';
    const extras = cfg.files.filter((f) => f.role !== 'exe');
    let extraLines = '';
    if (template === INNO_TEMPLATE) {
        extraLines = extras.map((f) => `Source: "${path.resolve(root, f.path).replace(/\\/g, '/')}"; DestDir: "{app}${f.subDir ? '\\' + f.subDir : ''}"; Flags: ignoreversion`).join('\n');
        return template
            .replace(/\{\{APP_NAME\}\}/g, cfg.appName)
            .replace(/\{\{APP_VERSION\}\}/g, cfg.appVersion)
            .replace(/\{\{OUTPUT_DIR\}\}/g, outputDir)
            .replace(/\{\{OUT_BASE\}\}/g, cfg.outBase)
            .replace(/\{\{ICON\}\}/g, iconPath || '')
            .replace(/\{\{EXE\}\}/g, path.resolve(root, exeName).replace(/\\/g, '/'))
            .replace(/\{\{EXE_NAME\}\}/g, path.basename(exeName))
            .replace(/\{\{EXTRA_FILES\}\}/g, extraLines);
    }
    if (template === NSIS_TEMPLATE) {
        extraLines = extras.map((f) => `  File "/oname=${f.subDir ? f.subDir + '/' : ''}${path.basename(f.path)}" "${path.resolve(root, f.path).replace(/\\/g, '/')}"`).join('\n');
        return template
            .replace(/\{\{APP_NAME\}\}/g, cfg.appName)
            .replace(/\{\{OUTPUT_DIR\}\}/g, outputDir)
            .replace(/\{\{OUT_BASE\}\}/g, cfg.outBase)
            .replace(/\{\{EXE\}\}/g, path.resolve(root, exeName).replace(/\\/g, '/'))
            .replace(/\{\{EXE_NAME\}\}/g, path.basename(exeName))
            .replace(/\{\{EXTRA_FILES\}\}/g, extraLines);
    }
    if (template === WIX_TEMPLATE) {
        // Files are grouped by their destination subDir; nested directories
        // are rendered as nested <Directory> elements under INSTALLFOLDER.
        const all = [{ path: exeName, subDir: '' }].concat(extras.map((f) => ({ path: f.path, subDir: f.subDir || '' })));
        const tree = { children: new Map(), files: [] };
        const getNode = (segments) => {
            let node = tree;
            for (const s of segments) {
                if (!node.children.has(s)) node.children.set(s, { children: new Map(), files: [] });
                node = node.children.get(s);
            }
            return node;
        };
        for (const f of all) {
            const segs = f.subDir ? f.subDir.split('/') : [];
            getNode(segs).files.push(f);
        }
        let compIdx = 0;
        let dirEntries = '';
        let featureRefs = '';
        const renderNode = (node, depth) => {
            const pad = '          '.repeat(depth + 1);
            const padIn = '            '.repeat(depth + 1);
            for (const [name, child] of node.children) {
                dirEntries += `${pad}<Directory Id="Dir${compIdx++}" Name="${name}">\n`;
                renderNode(child, depth + 1);
                dirEntries += `${pad}</Directory>\n`;
            }
            for (const f of node.files) {
                const compId = `Cmp${compIdx}`;
                dirEntries += `${padIn}<Component Id="${compId}" Guid="${guid()}">\n`;
                dirEntries += `${padIn}  <File Id="File${compIdx}" Source="${path.resolve(root, f.path).replace(/\\/g, '/')}" KeyPath="yes"/>\n`;
                dirEntries += `${padIn}</Component>\n`;
                featureRefs += `      <ComponentRef Id="${compId}"/>\n`;
                compIdx++;
            }
        };
        renderNode(tree, 0);
        return template
            .replace(/\{\{APP_NAME\}\}/g, cfg.appName)
            .replace(/\{\{VERSION\}\}/g, cfg.appVersion)
            .replace(/\{\{UPGRADE_GUID\}\}/g, cfg.upgradeGuid || guid())
            .replace(/\{\{DIR_ENTRIES\}\}/g, dirEntries)
            .replace(/\{\{FEATURE_REFS\}\}/g, featureRefs);
    }
    return template;
}

