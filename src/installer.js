/**
 * Initializes installer configuration via interactive wizard.
 * Creates installer/installer.json and installer script template.
 * 
 * Flow:
 * 1. Load .brix project config
 * 2. Find built exe in Brix_Works/
 * 2. Prompt for installer type (zip/inno/nsis/msi) with tool availability
 * 3. Prompt for files to include (folders preserve structure)
 * 4. Generate installer.json + script template (installer/installer.<ext>)
 * 5. Output next steps
 * 
 * Security: File selection limited to project root; path traversal prevented.
 * 
 * @param {string} project - Project directory path
 * @param {Object} options - CLI options (type, files, name, appVersion, outBase)
 */
async function initInstaller(project, options) {
    const { root, config } = await loadProjectConfig(project);

    const exe = findBuiltExe(root, config);
    if (!exe) {
        console.log(chalk.yellow(`   ⚠ No built exe in ${path.join(root, 'Brix_Works')} — build it first: brix build`));
    }

    let type = options.type;
    if (!type) {
        const templates = await listInstallerTemplates();
        const picked = await promptList({
            message: chalk.cyan('Pick an installer type (available in the Brix install folder):'),
            choices: templates.map((t) => ({ label: t.label, hint: t.hint })),
            multi: false
        });
        if (picked === -1 || picked === null) {
            console.log(chalk.gray('Cancelled.'));
            return;
        }
        type = templates[picked].type;
    }
    if (!TYPES[type]) throw new Error(`Unknown installer type: ${type} (zip | inno | nsis | msi)`);

    // Files to include — pick whole folders (their structure is preserved
    // on install) or individual root files.
    const { folders, files } = await listProjectItems(root);
    const allFiles = await listProjectFiles(root);
    let pickedFiles; // [{ path, subDir }]
    if (options.files) {
        pickedFiles = options.files.split(',').map((f) => f.trim()).filter(Boolean);
        const expanded = [];
        for (const f of pickedFiles) {
            if (folders.some((d) => d.name === f)) {
                expanded.push(...(await collectFolderFiles(root, f)).map((x) => ({ path: x.path, subDir: x.subDir })));
            } else if (allFiles.some((x) => x.name === f)) {
                expanded.push({ path: f, subDir: '' });
            } else {
                console.log(chalk.yellow(`   ⚠ Not found: ${f}`));
            }
        }
        pickedFiles = expanded;
    } else {
        console.log(chalk.cyan(`\nRoot of ${path.relative(process.cwd(), root) || '.'} — pick folders to ship (whole structure is kept) or single files:`));
        const defaults = [];
        const entryDir = config.entry ? config.entry.split('/')[0] : null;
        if (entryDir && folders.some((d) => d.name === entryDir)) {
            defaults.push(folders.findIndex((d) => d.name === entryDir));
        } else if (folders.length) {
            defaults.push(0);
        }
        const readmeIdx = files.findIndex((f) => /^readme\.(md|txt)$/i.test(f.name));
        if (readmeIdx >= 0) defaults.push(folders.length + readmeIdx);
        const licenseIdx = files.findIndex((f) => /^license/i.test(f.name));
        if (licenseIdx >= 0) defaults.push(folders.length + licenseIdx);
        const choices = [
            ...folders.map((d) => ({ label: `${d.name}/`, hint: chalk.gray(`folder (${d.count} files)`), i: -1 })),
            ...files.map((f) => ({ label: f.name, hint: formatBytes(f.size), i: -1 }))
        ].map((c, i) => ({ ...c, i }));

        const picked = await promptList({
            message: chalk.cyan('Select what to install (space to toggle):'),
            choices,
            multi: true,
            defaults
        });
        if (picked === null) {
            console.log(chalk.gray('Cancelled.'));
            return;
        }
        pickedFiles = [];
        for (const i of picked) {
            const c = choices[i];
            if (!c) continue;
            const isFolder = c.label.endsWith('/');
            const name = isFolder ? c.label.slice(0, -1) : c.label;
            if (isFolder) {
                pickedFiles.push(...(await collectFolderFiles(root, name)).map((x) => ({ path: x.path, subDir: x.subDir })));
            } else {
                pickedFiles.push({ path: name, subDir: '' });
            }
        }
    }

    const exeName = exe ? path.relative(root, exe).replace(/\\/g, '/') : null;
    const hasExe = exeName && pickedFiles.some((f) => f.path === exeName);
    if (!hasExe && exeName) {
        pickedFiles.unshift({ path: exeName, subDir: '', role: 'exe' }); // the app exe is always installed
    }

    const appName = options.name || config.name;
    const appVersion = options.appVersion || config.version || '1.0.0';
    const outBase = options.outBase || sanitize(appName) + '-setup';

    const cfg = {
        type,
        appName,
        appVersion,
        outBase,
        outputDir: 'installer/dist',
        files: pickedFiles.map((f) => ({
            path: f.path,
            role: f.role || (f.path === exeName ? 'exe' : 'extra'),
            subDir: f.subDir || ''
        })),
        exeName: exeName || sanitize(appName) + '.exe',
        icon: config.icon || undefined
    };

    await writeInstallerConfig(root, cfg);
    console.log(chalk.green(`\n✔ Installer config written to installer/installer.json`));
    console.log(chalk.gray(`   ${cfg.files.length} files (${formatBytes(cfg.files.reduce((n, f) => n + (f.size || 0), 0))})`));
    const meta = TYPES[type];
    if (meta.template) {
        console.log(chalk.gray(`   Script: installer/installer.${meta.ext}`));
    }
    console.log(chalk.gray(`   Next: run ${chalk.bold(`brix make ${type}`)} to build it`));
}

