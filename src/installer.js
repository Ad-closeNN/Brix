/**
 * Builds an installer package from installer/installer.json config.
 * 
 * Flow:
 * 1. Load installer/installer.json (or create minimal config from .brix)
 * 2. Validate target type (zip/inno/nsis/msi)
 * 3. For zip: create portable zip with archiver (level 9 compression)
 * 4. For inno/nsis/msi: render template → write script → invoke toolchain
 * 5. Output built installer path and size
 * 
 * Security:
 * - Toolchain invoked via execFile (no shell)
 * - File paths resolved absolutely, traversal prevented
 * - Tool lookup via findTool (PATH + known locations)
 * - No shell injection possible
 * 
 * @param {string} target - Installer type: zip | inno | nsis | msi
 * @param {Object} options - CLI options (project, out, name, appVersion)
 */
async function makeInstaller(target, options) {
    const root = path.resolve(options.project || process.cwd());
    const cfgPath = path.join(root, 'installer', 'installer.json');
    let cfg = null;
    if (await fs.pathExists(cfgPath)) {
        cfg = await fs.readJson(cfgPath);
    }
    const targetType = target || (cfg && cfg.type) || null;
    if (!targetType) {
        throw new Error('No installer target given. Run "brix init installer" first, or pass a target: brix make zip | inno | nsis | msi');
    }
    if (!TYPES[targetType]) {
        throw new Error(`Unknown installer target: ${targetType} (zip | inno | nsis | msi)`);
    }

    if (cfg) {
        cfg.type = targetType;
        if (options.name) cfg.appName = options.name;
        if (options.appVersion) cfg.appVersion = options.appVersion;
        await writeInstallerConfig(root, cfg);
    } else {
        const { config } = await loadProjectConfig(root);
        const exe = findBuiltExe(root, config);
        cfg = {
            type: targetType,
            appName: config.name,
            appVersion: config.version || '1.0.0',
            outBase: sanitize(config.name) + '-setup',
            outputDir: 'installer/dist',
            files: exe ? [{ path: path.relative(root, exe).replace(/\\/g, '/'), role: 'exe', subDir: '' }] : [],
            exeName: exe ? path.relative(root, exe).replace(/\\/g, '/') : sanitize(config.name) + '.exe',
            icon: config.icon || undefined
        };
    }

    const outputDir = options.out
        ? path.resolve(options.out)
        : path.isAbsolute(cfg.outputDir || '')
            ? cfg.outputDir
            : path.resolve(root, cfg.outputDir || 'installer/dist');
    const meta = TYPES[targetType];

    if (targetType === 'zip') {
        const exeEntry = cfg.files.find((f) => f.role === 'exe') || cfg.files[0];
        if (!exeEntry || !(await fs.pathExists(path.join(root, exeEntry.path)))) {
            throw new Error(`App exe not found (${exeEntry ? exeEntry.path : 'none'} in installer.json). Build it first: brix build`);
        }
        await fs.ensureDir(outputDir);
        const zipPath = path.join(outputDir, `${cfg.outBase}-portable.zip`);
        const archiver = require('archiver');
        const output = fs.createWriteStream(zipPath);
        const archive = archiver('zip', { zlib: { level: 9 } });
        archive.pipe(output);
        for (const f of cfg.files) {
            const abs = path.join(root, f.path);
            if (await fs.pathExists(abs)) {
                const zipName = (f.subDir ? f.subDir + '/' : '') + path.basename(f.path);
                archive.file(abs, { name: zipName });
            }
        }
        await archive.finalize();
        await new Promise((resolve, reject) => {
            output.on('close', resolve);
            output.on('error', reject);
        });
        console.log(chalk.green(`✔ Portable zip: ${zipPath}`));
        console.log(chalk.gray(`   ${formatBytes((await fs.stat(zipPath)).size)}`));
        return;
    }

    // Real installers: generate the script, then run the toolchain.
    const script = renderTemplate(meta.template, { ...cfg, outputDir }, root);
    const scriptPath = path.join(root, 'installer', `installer.${meta.ext}`);
    await fs.ensureDir(path.dirname(scriptPath));
    await fs.writeFile(scriptPath, script, 'utf8');

    if (targetType === 'inno') {
        const iscc = await findTool('iscc');
        if (!iscc) {
            throw new Error('Inno Setup not found. Install it from https://jrsoftware.org/isinfo.php (iscc.exe goes in PATH) and re-run: brix make inno');
        }
        console.log(chalk.gray(`   Running ${iscc} ...`));
        const res = await run(iscc, ['/Qp', scriptPath]);
        const built = path.join(outputDir, `${cfg.outBase}.exe`);
        if (res.code === 0 && (await fs.pathExists(built))) {
            console.log(chalk.green(`✔ Setup exe: ${built}`));
            console.log(chalk.gray(`   ${formatBytes((await fs.stat(built)).size)}`));
        } else {
            console.error(chalk.red(`✖ Inno Setup failed (exit ${res.code}):`));
            console.error(res.err || res.out);
            process.exitCode = 1;
        }
        return;
    }

    if (targetType === 'nsis') {
        const makensis = await findTool('makensis');
        if (!makensis) {
            throw new Error('NSIS not found. Install it from https://nsis.sourceforge.io/ (makensis.exe goes in PATH) and re-run: brix make nsis');
        }
        console.log(chalk.gray(`   Running ${makensis} ...`));
        const res = await run(makensis, ['/V2', scriptPath]);
        const built = path.join(outputDir, `${cfg.outBase}.exe`);
        if (res.code === 0 && (await fs.pathExists(built))) {
            console.log(chalk.green(`✔ NSIS installer: ${built}`));
            console.log(chalk.gray(`   ${formatBytes((await fs.stat(built)).size)}`));
        } else {
            console.error(chalk.red(`✖ NSIS failed (exit ${res.code}):`));
            console.error(res.err || res.out);
            process.exitCode = 1;
        }
        return;
    }

    if (targetType === 'msi') {
        const candle = await findTool('candle');
        const wixCli = await findTool('wix');
        await fs.ensureDir(outputDir);
        if (wixCli && !candle) {
            // WiX v4+: wix build path/to/installer.wxs -o out.msi
            console.log(chalk.gray(`   Running ${wixCli} build ...`));
            const res = await run(wixCli, ['build', scriptPath, '-o', path.join(outputDir, `${cfg.outBase}.msi`)]);
            const built = path.join(outputDir, `${cfg.outBase}.msi`);
            if (res.code === 0 && (await fs.pathExists(built))) {
                console.log(chalk.green(`✔ MSI: ${built}`));
                console.log(chalk.gray(`   ${formatBytes((await fs.stat(built)).size)}`));
            } else {
                console.error(chalk.red(`✖ WiX failed (exit ${res.code}):`));
                console.error(res.err || res.out);
                process.exitCode = 1;
            }
            return;
        }
        if (!candle) {
            throw new Error('WiX toolset not found. Install it from https://wixtoolset.org/ (candle.exe + light.exe in PATH) and re-run: brix make msi');
        }
        const light = await findTool('light');
        const wixobj = path.join(os.tmpdir(), `${cfg.outBase}.wixobj`);
        console.log(chalk.gray(`   Running ${candle} ...`));
        const cRes = await run(candle, ['-out', wixobj, scriptPath]);
        if (cRes.code !== 0) {
            console.error(chalk.red(`✖ candle failed (exit ${cRes.code}):`));
            console.error(cRes.err || cRes.out);
            process.exitCode = 1;
            return;
        }
        console.log(chalk.gray(`   Running ${light} ...`));
        const built = path.join(outputDir, `${cfg.outBase}.msi`);
        const lRes = await run(light, ['-out', built, wixobj]);
        if (lRes.code === 0 && (await fs.pathExists(built))) {
            console.log(chalk.green(`✔ MSI: ${built}`));
            console.log(chalk.gray(`   ${formatBytes((await fs.stat(built)).size)}`));
        } else {
            console.error(chalk.red(`✖ light failed (exit ${lRes.code}):`));
            console.error(lRes.err || lRes.out);
            process.exitCode = 1;
        }
        return;
    }
}

